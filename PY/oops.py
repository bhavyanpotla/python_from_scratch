# Q5: Collatz Conjecture Analysis

def collatz_rec(n, seq=None):
    """Recursive version: returns the list of steps taken to reach 1."""
    if seq is None: 
        seq = []
    seq.append(n)
    
    if n == 1:
        return seq
    
    # If even: n/2 | If odd: 3n+1
    if n % 2 == 0:
        return collatz_rec(n // 2, seq)
    else:
        return collatz_rec(3 * n + 1, seq)

def collatz_while(n):
    """While loop version: returns the list of steps taken to reach 1."""
    seq = []
    temp_n = n
    while temp_n != 1:
        seq.append(temp_n)
        if temp_n % 2 == 0:
            temp_n //= 2
        else:
            temp_n = 3 * temp_n + 1
    seq.append(1)
    return seq


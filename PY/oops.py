# 2. Find which number 1-50 takes the most steps
max_steps = 0
best_num = 0

for i in range(1, 51):
    # Using the recursive function to find the sequence
    # Steps = Total numbers in sequence minus the starting number
    current_seq = collatz_rec(i, seq=None) 
    steps = len(current_seq) - 1
    
    if steps > max_steps:
        max_steps = steps
        best_num = i

print("-" * 30)
print(f"Number between 1-50 with most steps: {best_num}")
print(f"Total step count: {max_steps}")

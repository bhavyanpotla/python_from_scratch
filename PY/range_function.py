# range(start , stop , step_size) by default the start is 0 and step_size is 1
"""
range(5)        0 1 2 3 4
range(2,6)      2 3 4 5
range(2,6,2)    2,4
"""
a = range(5)
for i in a:
    print(i)
b = range(2,6)
for i in b:
    print(i)
c = range(2,6,2)
for i in c:
    print(i)
d = range(-1,-10,-1)
for i in d:
    print(i)

for i in range(1,6):
    print('bhavyan naidu')
